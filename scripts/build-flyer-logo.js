// One-time asset build: turns logo.png into a small deflated RGB buffer that
// lib/pdf.js can embed directly, so the flyer function needs no image decoding
// at runtime. Re-run this if logo.png ever changes.
//   node scripts/build-flyer-logo.js
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'logo.png');
const OUT = path.join(ROOT, 'netlify', 'functions', 'lib', 'flyer-logo.js');
const TARGET = 200;             // output size in pixels (square)
const BACKDROP = [255, 255, 255]; // the flyer's logo card is white

function decodePng(buf) {
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error('not a PNG');
  const width = buf.readUInt32BE(16);
  const height = buf.readUInt32BE(20);
  const bitDepth = buf[24];
  const colorType = buf[25];
  const interlace = buf[28];
  if (bitDepth !== 8 || interlace !== 0 || (colorType !== 6 && colorType !== 2)) {
    throw new Error(`unsupported PNG (bitDepth ${bitDepth}, colorType ${colorType}, interlace ${interlace})`);
  }
  const channels = colorType === 6 ? 4 : 3;

  const idat = [];
  let pos = 8;
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos);
    const type = buf.toString('latin1', pos + 4, pos + 8);
    if (type === 'IDAT') idat.push(buf.slice(pos + 8, pos + 8 + len));
    if (type === 'IEND') break;
    pos += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));

  const bpp = channels;
  const stride = width * bpp;
  const out = Buffer.alloc(height * stride);
  let rp = 0;
  for (let y = 0; y < height; y++) {
    const filter = raw[rp++];
    const row = raw.slice(rp, rp + stride);
    rp += stride;
    const cur = out.slice(y * stride, (y + 1) * stride);
    const prior = y > 0 ? out.slice((y - 1) * stride, y * stride) : Buffer.alloc(stride);
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? cur[x - bpp] : 0;
      const b = prior[x];
      const c = x >= bpp ? prior[x - bpp] : 0;
      let value = row[x];
      switch (filter) {
        case 0: break;
        case 1: value += a; break;
        case 2: value += b; break;
        case 3: value += (a + b) >> 1; break;
        case 4: {
          const p = a + b - c;
          const pa = Math.abs(p - a);
          const pb = Math.abs(p - b);
          const pc = Math.abs(p - c);
          value += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
          break;
        }
        default: throw new Error(`unknown PNG filter ${filter}`);
      }
      cur[x] = value & 0xff;
    }
  }
  return { width, height, channels, pixels: out };
}

// Box-filter downscale straight onto the backdrop colour, dropping the alpha.
function downscaleToRgb(img, size) {
  const { width, height, channels, pixels } = img;
  const out = Buffer.alloc(size * size * 3);
  for (let oy = 0; oy < size; oy++) {
    const y0 = Math.floor((oy * height) / size);
    const y1 = Math.max(y0 + 1, Math.floor(((oy + 1) * height) / size));
    for (let ox = 0; ox < size; ox++) {
      const x0 = Math.floor((ox * width) / size);
      const x1 = Math.max(x0 + 1, Math.floor(((ox + 1) * width) / size));
      let r = 0, g = 0, b = 0, n = 0;
      for (let y = y0; y < y1; y++) {
        for (let x = x0; x < x1; x++) {
          const i = (y * width + x) * channels;
          const alpha = channels === 4 ? pixels[i + 3] / 255 : 1;
          r += pixels[i] * alpha + BACKDROP[0] * (1 - alpha);
          g += pixels[i + 1] * alpha + BACKDROP[1] * (1 - alpha);
          b += pixels[i + 2] * alpha + BACKDROP[2] * (1 - alpha);
          n++;
        }
      }
      const o = (oy * size + ox) * 3;
      out[o] = Math.round(r / n);
      out[o + 1] = Math.round(g / n);
      out[o + 2] = Math.round(b / n);
    }
  }
  return out;
}

const img = decodePng(fs.readFileSync(SRC));
console.log(`source: ${img.width}x${img.height}, ${img.channels} channels`);
const rgb = downscaleToRgb(img, TARGET);
const deflated = zlib.deflateSync(rgb, { level: 9 });
const b64 = deflated.toString('base64');

const lines = b64.match(/.{1,96}/g).map((l) => `  '${l}',`).join('\n');
fs.writeFileSync(
  OUT,
  `// Generated by scripts/build-flyer-logo.js from logo.png — do not edit by hand.\n` +
  `// ${TARGET}x${TARGET} 8-bit RGB, composited on white, zlib-deflated for direct\n` +
  `// embedding as a PDF image XObject.\n` +
  `const SIZE = ${TARGET};\n\n` +
  `const DATA = [\n${lines}\n].join('');\n\n` +
  `module.exports = { width: SIZE, height: SIZE, data: Buffer.from(DATA, 'base64') };\n`
);
console.log(`wrote ${OUT} — ${rgb.length} raw bytes -> ${deflated.length} deflated (${b64.length} base64 chars)`);
